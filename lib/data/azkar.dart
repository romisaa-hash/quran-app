class Zikr {
  final String text;
  final int count;
  final String source;
  const Zikr(this.text, {this.count = 1, this.source = ''});
}

class AzkarCategory {
  final String title;
  final String icon;
  final List<Zikr> items;
  const AzkarCategory(this.title, this.icon, this.items);
}

